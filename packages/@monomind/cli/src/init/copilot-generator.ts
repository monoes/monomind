/**
 * Mesh inbox bridge for GitHub Copilot CLI and Hermes. Neither has a per-prompt
 * hook whose stdout reaches the model as plain text, so each gets the shared
 * .claude/helpers/mesh-inbox.cjs output wrapped in the JSON its hook protocol reads:
 *  - Copilot: `sessionStart` and `postToolUse` hooks return `{"additionalContext"}`.
 *    Config-file `userPromptSubmitted` hooks have their output dropped, so the
 *    inbox is read before the first turn and after every tool call instead.
 *  - Hermes: `pre_llm_call` shell hooks return `{"context"}`, injected into the
 *    turn's user message. Hermes reads hooks only from ~/.hermes/config.yaml.
 * One script serves both: it prints both keys, and each CLI ignores the other's.
 */

export const COPILOT_MESH_SCRIPT = '.github/hooks/monomind-mesh.cjs';
export const COPILOT_HOOKS_FILE = '.github/hooks/monomind-mesh.json';

export function generateMeshBridgeScript(): string {
  return `#!/usr/bin/env node
'use strict';
// monomind mesh inbox bridge for GitHub Copilot CLI and Hermes (generated by monomind init).
// Runs .claude/helpers/mesh-inbox.cjs and returns its [MESH] block as hook JSON:
// {"additionalContext"} for Copilot, {"context"} for Hermes. Silent, exit 0 on any failure.
//
// Hermes reads hooks only from ~/.hermes/config.yaml; opt in there with
//   hooks:
//     pre_llm_call:
//       - command: "node /absolute/path/to/this/project/.github/hooks/monomind-mesh.cjs"
// and approve it once (hermes hooks list / --accept-hooks).
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

let input = '';
process.stdin.on('data', (c) => { input += c; });
process.stdin.on('end', () => {
  let payload = {};
  try { payload = JSON.parse(input || '{}'); } catch (_) { process.exit(0); }
  let dir = typeof payload.cwd === 'string' && payload.cwd ? payload.cwd : process.cwd();
  let helper = '';
  for (let i = 0; i < 12; i++) {
    const candidate = path.join(dir, '.claude', 'helpers', 'mesh-inbox.cjs');
    if (fs.existsSync(candidate)) { helper = candidate; break; }
    const up = path.dirname(dir);
    if (up === dir) break;
    dir = up;
  }
  if (!helper) process.exit(0);
  try {
    // Spawned, not required: the helper walks its own ancestor pids to the CLI that started the MCP server.
    const r = spawnSync(process.execPath, [helper], { encoding: 'utf-8', timeout: 3000, cwd: dir });
    const text = r && r.status === 0 && r.stdout ? r.stdout.trim() : '';
    if (text) process.stdout.write(JSON.stringify({ additionalContext: text, context: text }));
  } catch (_) {}
  process.exit(0);
});
`;
}

/** Copilot CLI hook file: first-turn identity (sessionStart) and inbox after each tool call. */
export function generateCopilotHooksJson(): string {
  const command = {
    type: 'command',
    bash: `node ${COPILOT_MESH_SCRIPT}`,
    timeoutSec: 5,
  };
  return `${JSON.stringify(
    { version: 1, hooks: { sessionStart: [command], postToolUse: [command] } },
    null,
    2,
  )}\n`;
}
