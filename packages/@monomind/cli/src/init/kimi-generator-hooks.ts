/**
 * kimi-code Tier 2 hook gate bridge script.
 * File-size sweep: split out of kimi-generator.ts.
 *
 * Kimi hooks and Claude hooks share the same protocol: JSON payload on stdin,
 * exit 0 = allow, exit 2 = block with the reason on stderr. This script
 * translates kimi's PreToolUse payload into the {tool_name, tool_input}
 * envelope the existing .claude/helpers/hook-handler.cjs gates consume, and
 * maps their exit code straight back. Nothing in .claude/helpers is modified.
 *
 * The script must be free of backticks and ${...} outside its own template
 * usage — it is embedded into a TypeScript template literal by the caller.
 */

export function generateKimiGateScript(): string {
  return `// monomind gate bridge for Kimi Code hooks (generated by monomind init --kimicode).
// Reads kimi's hook payload on stdin, forwards to .claude/helpers/hook-handler.cjs,
// maps exit code 2 back to a block. Fails OPEN when the handler is absent or errors,
// matching both platforms' "hook errors never block" policy.
import { spawnSync } from "node:child_process";
import * as fs from "node:fs";
import * as path from "node:path";

let input = "";
process.stdin.on("data", (c) => { input += c; });
process.stdin.on("end", () => {
  let payload = {};
  try { payload = JSON.parse(input || "{}"); } catch (e) { process.exit(0); }
  const cwd = payload.cwd || process.cwd();
  const handler = path.join(cwd, ".claude", "helpers", "hook-handler.cjs");
  if (!fs.existsSync(handler)) process.exit(0); // gates not installed -> nothing to enforce

  const tool = payload.tool_name || "";
  let event = null;
  let gateInput = {};
  if (tool === "Bash") {
    event = "pre-bash";
    gateInput = { command: payload.tool_input && payload.tool_input.command };
  } else if (tool === "Write" || tool === "Edit" || tool === "MultiEdit") {
    event = "pre-write";
    gateInput = payload.tool_input || {};
  } else if (tool === "Grep" || tool === "Glob") {
    // Graph-first gate: search tools must consult monograph before grep/glob
    // (once-per-session block, then warn) — same rule as Claude's pre-search.
    event = "pre-search";
    gateInput = payload.tool_input || {};
  }
  if (!event) process.exit(0);

  // Inside a monomind org role, quiet the hook handler. Set here, on the
  // handler process only: kimi gives hooks and its shell tool one env, so a
  // role-wide setting would reach every command the role runs.
  const orgRoleEnv = process.env.MONOMIND_ORG_ROLE
    ? { MONOMIND_HOOK_QUIET: "1", MONOMIND_GRAPH_GATE: "off", MONOMIND_SDK_AGENT: "1" }
    : {};
  let r;
  try {
    r = spawnSync(process.execPath, [handler, event], {
      input: JSON.stringify({ tool_name: tool, tool_input: gateInput, session_id: payload.session_id || "" }),
      encoding: "utf-8",
      timeout: 5000,
      cwd: cwd,
      env: Object.assign({}, process.env, orgRoleEnv, { CLAUDE_PROJECT_DIR: cwd }),
    });
  } catch (e) {
    process.exit(0);
  }
  if (!r || r.status !== 2) process.exit(0);

  let reason = "blocked by monomind gate";
  const lines = (r.stderr || "").split("\\n");
  for (let i = 0; i < lines.length; i++) {
    try {
      const obj = JSON.parse(lines[i]);
      if (obj && obj.decision === "block" && obj.reason) { reason = obj.reason; break; }
    } catch (e) {}
  }
  console.error("[monomind] " + reason);
  process.exit(2);
});
`;
}

/**
 * Mesh inbox bridge for kimi's `UserPromptSubmit` hook. Kimi appends a hook's
 * exit-0 stdout to the prompt context, so this only runs the shared
 * .claude/helpers/mesh-inbox.cjs and forwards what it prints. The helper finds
 * the session's hub credentials by walking its own ancestor pids, so it is
 * spawned (not required) and kimi stays among its ancestors. Always exits 0.
 * Kimi has no documented way for a hook to set a session title, so there is no
 * counterpart to .claude/helpers/mesh-title.cjs.
 */
export function generateKimiMeshScript(): string {
  return `// monomind mesh inbox bridge for Kimi Code hooks (generated by monomind init --kimicode).
// UserPromptSubmit: runs .claude/helpers/mesh-inbox.cjs and prints its [MESH] block to stdout,
// which kimi appends to the prompt context. Silent and exit 0 whenever anything is missing.
import { spawnSync } from "node:child_process";
import * as fs from "node:fs";
import * as path from "node:path";

let input = "";
process.stdin.on("data", (c) => { input += c; });
process.stdin.on("end", () => {
  let payload = {};
  try { payload = JSON.parse(input || "{}"); } catch (e) { process.exit(0); }
  const cwd = payload.cwd || process.cwd();
  const helper = path.join(cwd, ".claude", "helpers", "mesh-inbox.cjs");
  if (!fs.existsSync(helper)) process.exit(0);
  try {
    const r = spawnSync(process.execPath, [helper], { encoding: "utf-8", timeout: 3000, cwd: cwd });
    if (r && r.status === 0 && r.stdout) process.stdout.write(r.stdout);
  } catch (e) {}
  process.exit(0);
});
`;
}
