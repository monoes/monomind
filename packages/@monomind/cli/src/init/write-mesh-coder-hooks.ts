/**
 * Mesh inbox delivery for coder CLIs that read project-local hook config:
 * Qwen Code (`--target qwen`), Crush (`--target crush`) and Factory Droid
 * (`--platforms droid`). Each hook runs the shared .claude/helpers/mesh-inbox.cjs
 * unchanged; that helper finds the session's hub credentials by walking its own
 * ancestor pids, and all three CLIs run hooks and MCP servers as children of the
 * same process. Existing config is merged, never replaced; an unparseable file is
 * skipped with a warning.
 *
 * Qwen and Droid add exit-0 plain stdout of a UserPromptSubmit hook to the model
 * context (docs: qwenlm.github.io/qwen-code-docs .../features/hooks, docs.factory.com
 * /cli/configuration/hooks-guide). Crush has only PreToolUse and reads a JSON
 * `{"context": ...}` envelope, so it gets a small bridge script.
 * None of the three has a documented way for a hook to set a session title.
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import { mcpServerEntry } from '../platform-adapters/renderers/mcp.js';
import { atomicWriteFile } from './fs-helpers.js';
import type { InitOptions, InitResult } from './types.js';
import { writeHelpers } from './write-claude.js';

type Json = Record<string, unknown>;

const isObject = (v: unknown): v is Json =>
  typeof v === 'object' && v !== null && !Array.isArray(v);

/** `node <project dir var>/.claude/helpers/mesh-inbox.cjs`, with the cwd as a fallback. */
const inboxCommand = (dirVar: string): string =>
  `node "\${${dirVar}:-.}/.claude/helpers/mesh-inbox.cjs"`;

export const QWEN_MESH_COMMAND = inboxCommand('QWEN_PROJECT_DIR');
export const DROID_MESH_COMMAND = inboxCommand('FACTORY_PROJECT_DIR');
export const CRUSH_MESH_COMMAND = 'node "${CRUSH_PROJECT_DIR:-.}/.crush/hooks/monomind-mesh.cjs"';

const CRUSH_BRIDGE = '.crush/hooks/monomind-mesh.cjs';

/** Crush PreToolUse bridge: wraps the helper's [MESH] text as the `context` crush appends to the tool result. */
export function generateCrushMeshScript(): string {
  return `// monomind mesh inbox bridge for Crush hooks (generated by monomind init --target crush).
// PreToolUse: runs .claude/helpers/mesh-inbox.cjs and prints its [MESH] block as the
// {"context": ...} envelope crush appends to the tool result. Silent and exit 0 on any failure.
'use strict';
const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

let input = '';
process.stdin.on('data', (c) => { input += c; });
process.stdin.on('end', () => {
  try {
    let payload = {};
    try { payload = JSON.parse(input || '{}'); } catch (e) { process.exit(0); }
    const cwd = process.env.CRUSH_PROJECT_DIR || payload.cwd || process.cwd();
    const helper = path.join(cwd, '.claude', 'helpers', 'mesh-inbox.cjs');
    if (!fs.existsSync(helper)) process.exit(0);
    const r = spawnSync(process.execPath, [helper], { encoding: 'utf-8', timeout: 3000, cwd: cwd });
    const text = r && r.status === 0 && r.stdout ? r.stdout.trim() : '';
    if (text) process.stdout.write(JSON.stringify({ context: text }));
  } catch (e) {}
  process.exit(0);
});
`;
}

function readJson(file: string): Json | null | undefined {
  if (!fs.existsSync(file)) return undefined;
  try {
    const parsed: unknown = JSON.parse(fs.readFileSync(file, 'utf8'));
    return isObject(parsed) ? parsed : null;
  } catch {
    return null;
  }
}

/** Entry shaped `{matcher?, hooks:[{type:'command', command}]}` already running `command`. */
const hasCommand = (list: unknown, command: string): boolean =>
  Array.isArray(list) &&
  list.some(
    (e) =>
      isObject(e) &&
      Array.isArray(e.hooks) &&
      e.hooks.some((h) => isObject(h) && h.command === command),
  );

/**
 * Create or merge a JSON config file. `edit` mutates the parsed object and returns whether it
 * changed anything. Returns false (with a warning) when the file exists but is not a JSON object.
 */
function updateJson(
  targetDir: string,
  rel: string,
  result: InitResult,
  edit: (doc: Json) => boolean,
): boolean {
  const file = path.join(targetDir, rel);
  const existing = readJson(file);
  if (existing === null) {
    (result.warnings ??= []).push(`${rel}: not a JSON object; add the monomind mesh hook by hand`);
    return false;
  }
  const doc = existing ?? {};
  if (!edit(doc)) {
    result.skipped.push(rel);
    return true;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  atomicWriteFile(file, `${JSON.stringify(doc, null, 2)}\n`);
  (existing ? result.updated : result.created.files).push(rel);
  return true;
}

/** Add `{hooks:[command hook]}` to `container.UserPromptSubmit` unless that command is already there. */
function addPromptHook(container: Json, command: string, timeout: number): boolean {
  const list = Array.isArray(container.UserPromptSubmit) ? container.UserPromptSubmit : [];
  if (hasCommand(list, command)) return false;
  list.push({ hooks: [{ type: 'command', command, name: 'monomind-mesh', timeout }] });
  container.UserPromptSubmit = list;
  return true;
}

function addMcpServer(doc: Json, key: string, entry: Json, options: InitOptions): boolean {
  if (!options.mcp.monomind) return false;
  const servers = isObject(doc[key]) ? (doc[key] as Json) : {};
  if (servers.monomind && !options.force) return false;
  servers.monomind = entry;
  doc[key] = servers;
  return true;
}

/** `.qwen/settings.json`: monomind MCP server and the UserPromptSubmit mesh hook. */
export async function writeQwenFiles(
  targetDir: string,
  options: InitOptions,
  result: InitResult,
): Promise<void> {
  updateJson(targetDir, '.qwen/settings.json', result, (doc) => {
    const mcp = addMcpServer(
      doc,
      'mcpServers',
      mcpServerEntry('claude', {}, undefined, options.mcp.pin),
      options,
    );
    const hooks = isObject(doc.hooks) ? (doc.hooks as Json) : {};
    const hook = addPromptHook(hooks, QWEN_MESH_COMMAND, 5);
    doc.hooks = hooks;
    return mcp || hook;
  });
}

/**
 * Droid: the monomind MCP server in `.factory/mcp.json` (docs.factory.com/cli/configuration/mcp)
 * and the mesh hook in `.factory/hooks.json`, falling back to the `hooks` key of settings.json.
 */
export async function writeDroidMeshHook(
  targetDir: string,
  options: InitOptions,
  result: InitResult,
): Promise<void> {
  updateJson(targetDir, '.factory/mcp.json', result, (doc) =>
    addMcpServer(
      doc,
      'mcpServers',
      { type: 'stdio', ...mcpServerEntry('claude', {}, undefined, options.mcp.pin) },
      options,
    ),
  );
  const useSettings =
    !fs.existsSync(path.join(targetDir, '.factory/hooks.json')) &&
    fs.existsSync(path.join(targetDir, '.factory/settings.json'));
  if (useSettings) {
    updateJson(targetDir, '.factory/settings.json', result, (doc) => {
      const hooks = isObject(doc.hooks) ? (doc.hooks as Json) : {};
      const changed = addPromptHook(hooks, DROID_MESH_COMMAND, 5);
      doc.hooks = hooks;
      return changed;
    });
    return;
  }
  updateJson(targetDir, '.factory/hooks.json', result, (doc) =>
    addPromptHook(doc, DROID_MESH_COMMAND, 5),
  );
}

/** `crush.json`: monomind MCP server and a PreToolUse mesh hook, plus the bridge script. */
export async function writeCrushFiles(
  targetDir: string,
  options: InitOptions,
  result: InitResult,
): Promise<void> {
  const bridge = path.join(targetDir, CRUSH_BRIDGE);
  if (!fs.existsSync(bridge) || options.force) {
    fs.mkdirSync(path.dirname(bridge), { recursive: true });
    atomicWriteFile(bridge, generateCrushMeshScript());
    result.created.files.push(CRUSH_BRIDGE);
  } else {
    result.skipped.push(CRUSH_BRIDGE);
  }
  updateJson(targetDir, 'crush.json', result, (doc) => {
    const entry = {
      type: 'stdio',
      ...mcpServerEntry('claude', {}, undefined, options.mcp.pin),
    };
    const mcp = addMcpServer(doc, 'mcp', entry, options);
    const hooks = isObject(doc.hooks) ? (doc.hooks as Json) : {};
    const list = Array.isArray(hooks.PreToolUse) ? hooks.PreToolUse : [];
    const known = list.some((h) => isObject(h) && h.command === CRUSH_MESH_COMMAND);
    if (!known) list.push({ name: 'monomind-mesh', command: CRUSH_MESH_COMMAND, timeout: 5 });
    hooks.PreToolUse = list;
    doc.hooks = hooks;
    return mcp || !known;
  });
}

/**
 * Entry point for the executor: the qwen / crush targets and the droid platform. Their hooks run
 * the shared mesh-inbox.cjs helper, so it is written even when the Claude files are skipped.
 */
export async function writeMeshCoderHooks(
  targetDir: string,
  options: InitOptions,
  result: InitResult,
): Promise<void> {
  const qwen = options.components.qwen === true;
  const crush = options.components.crush === true;
  const droid = options.selectedPlatforms?.includes('droid') === true;
  if (!(qwen || crush || droid)) return;
  if (!options.components.helpers) await writeHelpers(targetDir, options, result);
  if (qwen) await writeQwenFiles(targetDir, options, result);
  if (crush) await writeCrushFiles(targetDir, options, result);
  if (droid) await writeDroidMeshHook(targetDir, options, result);
}
